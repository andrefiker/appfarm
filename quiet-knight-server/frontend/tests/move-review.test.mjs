import assert from 'node:assert/strict';
import { Chess } from 'chess.js';
import { positionAtPly, reviewStillValid } from '../src/move-review.ts';

const line = ['e4', 'd5', 'exd5', 'Qxd5'];
const selection = { gameId: 'table:1', line, ply: 2 };
assert.equal(reviewStillValid(selection, 'table:1', [...line, 'Nc3']), true);
assert.equal(reviewStillValid(selection, 'table:2', line), false, 'rematch resets review');
assert.equal(reviewStillValid(selection, 'table:1', line.slice(0, 3)), false, 'takeback resets review');
assert.equal(reviewStillValid(selection, 'table:1', ['e4', 'e5', 'Nf3', 'Nc6']), false, 'same-length replacement resets review');
assert.equal(reviewStillValid({ ...selection, ply: 5 }, 'table:1', line), false);
const live = new Chess(); line.forEach(san => live.move(san));
const before = live.fen();
assert.deepEqual(positionAtPly(line, 0).losses, { w: [], b: [] });
assert.deepEqual(positionAtPly(line, 3).losses, { w: [], b: ['p'] });
assert.deepEqual(positionAtPly(line, 4).losses, { w: ['p'], b: ['p'] });
assert.equal(positionAtPly(line, 3).position.d5.color, 'w');
assert.equal(positionAtPly(line, 4).fen, before);
assert.equal(live.fen(), before, 'review never changes the live game');
assert.deepEqual(line, ['e4', 'd5', 'exd5', 'Qxd5']);
assert.equal(positionAtPly(line, -1), null);
assert.equal(positionAtPly(line, 5), null);
assert.equal(positionAtPly(line, 1.5), null);
assert.equal(positionAtPly(['invalid'], 1), null);
const ep = positionAtPly(['e4', 'a6', 'e5', 'd5', 'exd6'], 5);
assert.equal(ep.position.d5, undefined);
assert.deepEqual(ep.losses.b, ['p'], 'en passant is a lost pawn');
const castle = positionAtPly(['e4', 'e5', 'Nf3', 'Nc6', 'Bc4', 'Nf6', 'O-O'], 7);
assert.equal(castle.position.g1.type, 'k');
assert.equal(castle.position.f1.type, 'r');
assert.deepEqual(castle.losses, { w: [], b: [] });
const promotion = positionAtPly(['a4', 'h5', 'a5', 'h4', 'a6', 'h3', 'axb7', 'hxg2', 'bxa8=Q', 'gxh1=Q'], 10);
assert.equal(promotion.position.a8.type, 'q');
assert.equal(promotion.position.h1.type, 'q');
assert.deepEqual(promotion.losses, { w: ['p', 'r'], b: ['p', 'r'] }, 'promoted pawns are not counted as lost');
assert.equal(positionAtPly(['f3', 'e5', 'g4', 'Qh4#'], 4).check, 'e1');
console.log('Move review: captures, en passant, promotion, castling, checkmate, live isolation and history boundaries passed.');
